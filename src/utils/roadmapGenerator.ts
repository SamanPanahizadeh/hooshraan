export interface RoadmapGenerationInput {
  companyName?: string;
  industry?: string;
  employeeCount?: string;
  dimensionScores: Record<string, number>;
  overallScore: number;
  maturityLevel: string;
  selectedPriorities?: Array<{
    title: string;
    category?: string;
    impact?: string;
    feasibility?: string;
  }>;
  customNotes?: string;
}

export function generateLocalRoadmapReport(data: RoadmapGenerationInput): string {
  const {
    companyName = 'سازمان در حال ارزیابی',
    industry = 'کسب‌وکار B2B و فناوری',
    employeeCount = '۵۰ تا ۲۵۰ نفر',
    dimensionScores,
    overallScore,
    maturityLevel,
    selectedPriorities = [],
    customNotes = 'تمرکز بر پیاده‌سازی کاربردی هوش مصنوعی و افزایش بهره‌وری تیم فروش',
  } = data;

  const dimStrategy = (dimensionScores?.strategy ?? 3.0).toFixed(1);
  const dimData = (dimensionScores?.data ?? 2.5).toFixed(1);
  const dimPeople = (dimensionScores?.people ?? 2.8).toFixed(1);
  const dimGov = (dimensionScores?.governance ?? 2.2).toFixed(1);
  const dimProcess = (dimensionScores?.process ?? 3.2).toFixed(1);
  const dimRoi = (dimensionScores?.roi ?? 2.4).toFixed(1);

  const prioritiesList =
    selectedPriorities.length > 0
      ? selectedPriorities
          .map(
            (p, idx) =>
              `${idx + 1}. **${p.title}** (${p.category || 'کاربرد تجاری'}): اولویت تأثیرگذاری ${p.impact || 'بالا'} و امکان‌سنجی ${p.feasibility || 'سریع'}`
          )
          .join('\n')
      : '۱. **راه‌اندازی Co-Pilot تحقیقات مشتری و ساخت Brief قبل از جلسات فروش**\n۲. **استانداردسازی پرامپت‌های B2B Outreach با متدولوژی S.C.O.O.V**\n۳. **تبدیل خودکار یادداشت‌های صوتی و متنی جلسات به فرمت استاندارد Customer Memory در CRM**';

  const weakestDimension =
    Number(dimGov) < 2.8
      ? 'حاکمیت، امنیت داده و مدیریت ریسک'
      : Number(dimData) < 2.8
      ? 'زیرساخت داده و یکپارچگی ابزارها'
      : Number(dimPeople) < 2.8
      ? 'فرهنگ سازمانی، آموزش و مهارت نیروی انسانی'
      : 'سنجش شاخص‌های مالی و بازگشت سرمایه (ROI)';

  return `# 📊 گزارش راهبردی ارزیابی بلوغ سازمانی و نقشه راه ۹۰ روزه اجرایی هوش مصنوعی

## ۱. خلاصه مدیریتی (Executive Summary)
سازمان **«${companyName}»** فعال در حوزه **«${industry}»** با مقیاس پرسنلی **«${employeeCount}»**، بر اساس ارزیابی جامع در ابعاد ۶‌گانه به امتیاز کل **${overallScore.toFixed(1)} از ۵.۰** دست یافته و در سطح بلوغ **«${maturityLevel}»** طبقه‌بندی می‌شود.

### ۳ اولویت کلیدی با بازگشت سرمایه سریع (Top 3 Quick Wins):
1. **راه‌اندازی دستیار هوشمند تحقیقات مشتری و رقبا (Pre-Meeting Research Brief)**: صرفه‌جویی هفتگی ۴ تا ۶ ساعت برای هر کارشناس فروش با خروجی ملموس در کمتر از ۳۰ روز.
2. **شخصی‌سازی ارتباطات B2B با مدل S.C.O.O.V**: ارتقای ۲.۵ برابری نرخ پاسخ‌دهی به ایمیل‌ها و پیام‌های Outreach بدون نیاز به تغییر زیرساخت‌های فعلی.
3. **ثبت استاندارد و هوشمند خلاصه جلسات در CRM (Customer Memory)**: حفظ کامل حافظه سازمانی مشتریان و تسریع چرخه تصمیم‌گیری مدیران خرید.

---

## ۲. تحلیل شکاف سازمانی و گلوگاه‌های پنهان (Gap & Bottleneck Analysis)
- **امتیازات ۶ بُعد ارزیابی‌شده**:
  - 🎯 **استراتژی و رهبری سازمانی:** ${dimStrategy} از ۵.۰
  - 🗄️ **زیرساخت داده و فناوری:** ${dimData} از ۵.۰
  - 👥 **سرمایه انسانی و فرهنگ:** ${dimPeople} از ۵.۰
  - 🛡️ **حاکمیت، امنیت و اخلاق داده:** ${dimGov} از ۵.۰
  - ⚙️ **فرآیندها و کاربردهای عملیاتی فروش:** ${dimProcess} از ۵.۰
  - 📈 **سنجش ارزش و بازگشت سرمایه (ROI):** ${dimRoi} از ۵.۰

- **گلوگاه بحرانی شناسایی‌شده**: مهم‌ترین نیاز به تقویت در حوزه **«${weakestDimension}»** قرار دارد.
- **ریسک انفعال (Cost of Inaction)**: حفظ فرآیندهای سنتی موجب کاهش مزیت رقابتی، طولانی‌تر شدن سیکل فروش و از دست رفتن فرصت‌های کلیدی در مواجهه با رقبای مجهز به هوش مصنوعی خواهد شد.

---

## ۳. اولویت‌های انتخابی و Use Caseهای کلیدی سازمان
${prioritiesList}

> **یادداشت و هدف محوری سازمان:** ${customNotes}

---

## ۴. نقشه راه ۹۰ روزه عملیاتی و گام‌به‌گام (90-Day Action Roadmap)

### 🔹 فاز ۱ (روزهای ۱ تا ۳۰) — پایه‌گذاری، استانداردسازی و Quick Wins
- **هدف**: ایجاد اولین دستاوردهای ملموس و خنثی‌سازی مقاومت روانی تیم.
- **اقدامات اجرایی**:
  1. تدوین دستورالعمل اولیه استفاده امن و اخلاقی از ابزارهای هوش مصنوعی (AI Security Guidelines) و عدم اشتراک‌گذاری داده‌های محرمانه.
  2. برگزاری کارگاه فشرده مهارت‌های پیشرفته پرامپت‌نویسی (چارچوب S.C.O.O.V) برای تیم فروش و بازاریابی.
  3. استقرار پایلوت دستیار تحقیق مشتریان (Customer Research Brief) برای جلسات با مشتریان هدف.
- **شاخص موفقیت فاز ۱**: حداقل ۸۰٪ اعضای تیم اولین گزارش‌های تحقیقاتی خود را با دستیار تولید کرده باشند.

### 🔹 فاز ۲ (روزهای ۳۱ تا ۶۰) — یکپارچه‌سازی با فرآیندها و توانمندسازی تیم
- **هدف**: نهادینه‌سازی ابزارها در جریان کار روزمره و اتصال به فرآیندهای CRM.
- **اقدامات اجرایی**:
  1. پیاده‌سازی متدولوژی ثبت حافظه مشتری (Customer Memory) در فرمت‌های استانداردهای CRM سازمان.
  2. اجرای جلسات هفتگی شبیه‌سازی و Role-Play با خریداران فرضی جهت ارتقای مهارت Discovery و Objection Handling.
  3. آغاز استقرار سیستماتیک Use Caseهای منتخب و پایش اولیه نرخ رضایت مشتریان.
- **شاخص موفقیت فاز ۲**: کاهش حداقل ۳۵٪ زمان امور اداری و دفتری کارشناسان فروش و آزادسازی زمان برای مذاکرات مستقیم.

### 🔹 فاز ۳ (روزهای ۶۱ تا ۹۰) — مقیاس‌پذیری، پایش ROI و ارتقای سطح بلوغ
- **هدف**: سنجش دقیق شاخص‌های مالی و برنامه‌ریزی برای گسترش به سایر دپارتمان‌ها.
- **اقدامات اجرایی**:
  1. راه‌اندازی داشبورد ارزیابی شاخص‌های کلیدی (کاهش طول چرخه فروش، نرخ بستن معاملات و صرفه‌جویی زمانی).
  2. گردآوری و مستندسازی بهترین پرامپت‌ها و ساخت «بانک دانش هوش مصنوعی سازمانی» (Internal Prompt Library).
  3. اجرای ارزیابی تشخیصی مجدد برای سنجش میزان رشد امتیاز بلوغ سازمانی نسبت به روز اول.
- **شاخص موفقیت فاز ۳**: دستیابی به نرخ بازگشت سرمایه مثبت (ROI > 300%) و ارتقای یک پله‌ای سطح بلوغ سازمانی.

---

## ۵. ماتریس حاکمیت، مدیریت تغییر و امنیت اطلاعات
- **پروتکل حفاظت از داده (Data Privacy)**: تفکیک داده‌های عمومی از داده‌های حساس مشتری و استفاده از تکنیک‌های Data Masking قبل از ارسال به مدل‌های زبان بزرگ.
- **استراتژی مدیریت تغییر**: معرفی هوش مصنوعی به عنوان ابزار تقویت توانایی انسان (Human-in-the-loop)، نه عامل جایگزینی نیروی کار.
- **نظام انگیزش**: ایجاد سازوکار تشویق برای کارشناسانی که بالاترین نوآوری را در استفاده از هوش مصنوعی نشان می‌دهند.

---

## ۶. شاخص‌های سنجش عملکرد (KPIs)
1. **کاهش زمان آماده‌سازی قبل از جلسه (Prep Time)**: از ۴۵ دقیقه به کمتر از ۱۰ دقیقه.
2. **افزایش نرخ پاسخ‌دهی لیدها (Response Rate)**: رشد حداقل ۲ برابری در ایمیل‌ها و پیام‌های Outreach.
3. **سرعت چرخه فروش (Sales Cycle Length)**: کاهش ۱۵ الی ۲۵ درصدی زمان انعقاد قراردادها.
4. **کیفیت و جامعیت داده‌های CRM**: افزایش دقت داده‌ها به بیش از ۹۰٪.
5. **نرخ پذیرش تیم (Adoption Rate)**: بیش از ۸۵٪ اعضای تیم به طور مستمر از شبیه‌سازها و دستیارهای هوشران استفاده کنند.`;
}
